#!/bin/sh
# Creates a Builder.app launcher bundle for an installed GNOME Builder.
#
# This does not bundle libraries: the app runs the Builder installed in
# PREFIX against the Homebrew GTK stack.
#
# Usage: make-app.sh [PREFIX] [DESTINATION_DIR]
#   PREFIX           where `meson install` put Builder (default: ~/.local/gnome-builder)
#   DESTINATION_DIR  where to create Builder.app (default: ~/Applications)

set -e

PREFIX="${1:-$HOME/.local/gnome-builder}"
DEST="${2:-$HOME/Applications}"
APP="$DEST/Builder.app"
ICON_SVG="$PREFIX/share/icons/hicolor/scalable/apps/org.gnome.Builder.svg"

if [ ! -x "$PREFIX/bin/gnome-builder" ]; then
  echo "error: $PREFIX/bin/gnome-builder not found, run 'meson install' first" >&2
  exit 1
fi

VERSION=$("$PREFIX/bin/gnome-builder" --version 2>/dev/null | sed 's/^GNOME Builder //' || true)
VERSION="${VERSION:-0}"

if command -v brew >/dev/null 2>&1; then
  BREW_PREFIX=$(brew --prefix)
elif [ -d /opt/homebrew ]; then
  BREW_PREFIX=/opt/homebrew
else
  BREW_PREFIX=/usr/local
fi

# Schemas installed under PREFIX must be compiled for the app to start
"$BREW_PREFIX/bin/glib-compile-schemas" "$PREFIX/share/glib-2.0/schemas"

# Builder's interface relies on the Adwaita icon theme
if [ ! -d "$BREW_PREFIX/share/icons/Adwaita" ]; then
  echo "warning: the Adwaita icon theme is missing, many icons will not show." >&2
  echo "         Install it with: brew install adwaita-icon-theme" >&2
fi

# Homebrew does not refresh the icon cache when a package installs icons, and
# GTK ignores icons that are not in a cache that exists. Rebuild it so that
# icons from packages such as libpanel are found.
for dir in "$BREW_PREFIX/share/icons/hicolor" "$PREFIX/share/icons/hicolor"; do
  if [ -d "$dir" ]; then
    "$BREW_PREFIX/bin/gtk4-update-icon-cache" -f -t -q "$dir" || \
      echo "warning: could not update the icon cache in $dir" >&2
  fi
done

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

cat > "$APP/Contents/MacOS/Builder" <<EOF
#!/bin/sh
# Generated by build-aux/macos/make-app.sh
PREFIX="$PREFIX"
BREW_PREFIX="$BREW_PREFIX"

export XDG_DATA_DIRS="\$PREFIX/share:\$BREW_PREFIX/share:/usr/local/share:/usr/share"
export GSETTINGS_SCHEMA_DIR="\$PREFIX/share/glib-2.0/schemas"
export GI_TYPELIB_PATH="\$PREFIX/lib/gnome-builder/girepository-1.0:\$BREW_PREFIX/lib/girepository-1.0"
export DYLD_FALLBACK_LIBRARY_PATH="\$PREFIX/lib:\$PREFIX/lib/gnome-builder:\$BREW_PREFIX/lib"

# Finder passes -psn_* arguments that GApplication does not understand
for arg in "\$@"; do
  shift
  case "\$arg" in
    -psn_*) ;;
    *) set -- "\$@" "\$arg" ;;
  esac
done

exec "\$PREFIX/bin/gnome-builder" "\$@"
EOF
chmod +x "$APP/Contents/MacOS/Builder"

cat > "$APP/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleExecutable</key><string>Builder</string>
  <key>CFBundleIdentifier</key><string>org.gnome.Builder</string>
  <key>CFBundleName</key><string>Builder</string>
  <key>CFBundleDisplayName</key><string>Builder</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleIconFile</key><string>Builder</string>
  <key>CFBundleShortVersionString</key><string>$VERSION</string>
  <key>CFBundleVersion</key><string>$VERSION</string>
  <key>LSApplicationCategoryType</key><string>public.app-category.developer-tools</string>
  <key>NSHighResolutionCapable</key><true/>
  <key>LSMinimumSystemVersion</key><string>13.0</string>
</dict>
</plist>
EOF
plutil -lint "$APP/Contents/Info.plist" >/dev/null

# Icon: render the SVG at every size an iconset needs
if [ -f "$ICON_SVG" ] && command -v rsvg-convert >/dev/null 2>&1; then
  ICONSET=$(mktemp -d)/Builder.iconset
  mkdir -p "$ICONSET"
  for size in 16 32 128 256 512; do
    rsvg-convert -w $size -h $size "$ICON_SVG" -o "$ICONSET/icon_${size}x${size}.png"
    rsvg-convert -w $((size * 2)) -h $((size * 2)) "$ICON_SVG" -o "$ICONSET/icon_${size}x${size}@2x.png"
  done
  iconutil -c icns "$ICONSET" -o "$APP/Contents/Resources/Builder.icns"
  rm -rf "$(dirname "$ICONSET")"
else
  echo "warning: no icon created (need $ICON_SVG and rsvg-convert)" >&2
fi

# An ad-hoc signature gives the bundle a stable identity, so macOS can
# remember the folder access you grant it (Documents, Desktop, ...).
codesign --force --deep --sign - "$APP" >/dev/null 2>&1 || \
  echo "warning: could not sign $APP, macOS may ask for folder access on every launch" >&2

echo "Created $APP"
echo
echo "Note: the first time you open a project in ~/Documents, ~/Desktop or ~/Downloads,"
echo "macOS asks whether Builder may access that folder. Until you answer, opening"
echo "the project appears to hang."
